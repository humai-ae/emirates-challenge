import type {
  Evidence,
  FlagAssignment,
  FlagDecision,
  FlagFix,
  FlagJudgment,
  FlagKind,
  FlagPerson,
  FlagSeenAgain,
  FlagSentBack,
  FlagStatus,
  FlagVerification,
  FlagWriting,
  ReportTo,
  Severity,
  SeverityReason,
  TextSource,
} from "@hrcc/shared";
import { Column, Entity, JoinColumn, ManyToOne, PrimaryColumn, type Relation } from "typeorm";
import { TeamEntity } from "./team.entity.js";

/** A cell of the flagged transaction; flags keep them in file order. */
export interface StoredCell {
  column: string;
  value: string;
}

/** A finding on its way to a decision, a fix and a check; keeps what its page shows. */
@Entity({ name: "flags" })
export class FlagEntity {
  /** "F-000913". */
  @PrimaryColumn({ type: "text" })
  id: string;

  @Column({ name: "run_id", type: "text" })
  runId: string;

  @Column({ name: "result_seq", type: "integer" })
  resultSeq: number;

  @Column({ type: "text" })
  kind: FlagKind;

  @Column({ type: "text" })
  status: FlagStatus;

  @Column({ name: "rule_id", type: "text" })
  ruleId: string;

  @Column({ name: "rule_version", type: "integer" })
  ruleVersion: number;

  @Column({ name: "rule_title", type: "text" })
  ruleTitle: string;

  @Column({ name: "transaction_ids", type: "text", array: true })
  transactionIds: string[];

  @Column({ name: "row_no", type: "integer" })
  rowNo: number;

  @Column({ name: "transaction_type", type: "text", nullable: true })
  transactionType: string | null;

  @Column({ type: "text", nullable: true })
  department: string | null;

  @Column({ name: "employee_id", type: "text", nullable: true })
  employeeId: string | null;

  @Column({ name: "requester_id", type: "text", nullable: true })
  requesterId: string | null;

  @Column({ type: "jsonb" })
  transaction: StoredCell[];

  @Column({ type: "jsonb" })
  people: FlagPerson[];

  @Column({ type: "jsonb" })
  evidence: Evidence[];

  @Column({ name: "explanation_en", type: "text" })
  explanationEn: string;

  @Column({ name: "explanation_ar", type: "text" })
  explanationAr: string;

  @Column({ name: "explanation_source_en", type: "text" })
  explanationSourceEn: TextSource;

  @Column({ name: "explanation_source_ar", type: "text" })
  explanationSourceAr: TextSource;

  /** Whether AI is rewriting the explanation and fix. */
  @Column({ type: "text" })
  writing: FlagWriting;

  /** The standard wording, built from the transaction and the rule: always one click away. */
  @Column({ name: "standard_explanation_en", type: "text" })
  standardExplanationEn: string;

  @Column({ name: "standard_explanation_ar", type: "text" })
  standardExplanationAr: string;

  @Column({ name: "standard_fix_en", type: "text" })
  standardFixEn: string;

  @Column({ name: "standard_fix_ar", type: "text" })
  standardFixAr: string;

  /** How sure AI was, for an AI judgment. */
  @Column({ type: "text", nullable: true })
  confidence: Severity | null;

  @Column({ type: "jsonb", nullable: true })
  judgment: FlagJudgment | null;

  @Column({ name: "suggested_fix_en", type: "text" })
  suggestedFixEn: string;

  @Column({ name: "suggested_fix_ar", type: "text" })
  suggestedFixAr: string;

  @Column({ type: "text" })
  severity: Severity;

  /** 1 High, 2 Medium, 3 Low: generated by the database from `severity`. */
  @Column({ name: "severity_rank", type: "smallint", insert: false, update: false })
  severityRank: number;

  @Column({ name: "severity_reasons", type: "jsonb" })
  severityReasons: SeverityReason[];

  @Column({ name: "owner_team_id", type: "uuid", nullable: true })
  ownerTeamId: string | null;

  @ManyToOne(() => TeamEntity, { nullable: true })
  @JoinColumn({ name: "owner_team_id" })
  ownerTeam: Relation<TeamEntity> | null;

  /** `YYYY-MM-DD`. */
  @Column({ name: "due_date", type: "date" })
  dueDate: string;

  @Column({ name: "report_to", type: "jsonb" })
  reportTo: ReportTo;

  @Column({ type: "jsonb", nullable: true })
  decision: FlagDecision | null;

  @Column({ name: "assignee_user_id", type: "uuid", nullable: true })
  assigneeId: string | null;

  @Column({ type: "jsonb", nullable: true })
  assignment: FlagAssignment | null;

  @Column({ type: "jsonb", nullable: true })
  fix: FlagFix | null;

  @Column({ type: "jsonb", nullable: true })
  verification: FlagVerification | null;

  @Column({ name: "sent_back", type: "jsonb", nullable: true })
  sentBack: FlagSentBack | null;

  @Column({ name: "seen_again", type: "jsonb" })
  seenAgain: FlagSeenAgain[];

  /** Who changed it last, for "Already confirmed by …". */
  @Column({ name: "last_changed_by", type: "text", nullable: true })
  lastChangedBy: string | null;

  @Column({ name: "row_version", type: "integer" })
  rowVersion: number;

  @Column({ name: "created_at", type: "timestamptz" })
  createdAt: Date;

  @Column({ name: "updated_at", type: "timestamptz" })
  updatedAt: Date;
}
